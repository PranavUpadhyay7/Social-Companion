const addMediaGallery = (clubber, profileIndex) => ({
  ...clubber,
  media: [
    {
      id: `${clubber.id}-profile`,
      type: "image",
      src: clubber.image,
      alt: `${clubber.name}'s profile photo`,
    },
    ...Array.from({ length: nightlifeMedia.length }, (_, mediaIndex) => ({
      id: `${clubber.id}-night-${mediaIndex + 1}`,
      type: "image",
      src: nightlifeMedia[(mediaIndex + profileIndex) % nightlifeMedia.length],
      alt: `${clubber.name}'s nightlife moment ${mediaIndex + 1}`,
    })),
  ],
});

